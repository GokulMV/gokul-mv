#!/usr/bin/env node
/**
 * Compiles the shelf's design file, src/shelf/Shelf.dc.html, into a Preact module.
 *
 * The design file holds a template and a logic class. The template language is small:
 * {{a.b}} lookups, <sc-for list as>, <sc-if value>, and a <helmet> for head tags.
 * Output:
 *   src/shelf/shelf.generated.js   the logic class, renderTree(values) → Preact vnodes, the tweakable props
 *   src/shelf/shelf.generated.css  the styles from the helmet
 *
 * Case is preserved (viewBox, onClick), which is why this has its own tag tokenizer.
 * Run with `npm run shelf`; `npm run dev` and `npm run build` run it first.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src/shelf/Shelf.dc.html');
const OUT_JS = join(ROOT, 'src/shelf/shelf.generated.js');
const OUT_CSS = join(ROOT, 'src/shelf/shelf.generated.css');
const VOID = new Set(['input', 'br', 'img', 'meta', 'link', 'hr']);
// The design canvas serves the résumé from its asset store; the site serves it from /public.
const ASSET_PATHS = { '/_blob/43da7d3578c29d1ed2ce3e345e33799a': '/Gokul_MV_Resume.pdf' };

const src = readFileSync(SRC, 'utf8');
const xdc = src.slice(src.indexOf('<x-dc>') + 6, src.indexOf('</x-dc>'));
const script = src.match(/<script type="text\/x-dc"[^>]*data-props='([^']*)'[^>]*>([\s\S]*?)<\/script>/);
if (!script) throw new Error('No <script type="text/x-dc"> with data-props in Shelf.dc.html');
const propsSpec = JSON.parse(script[1]);
const logicJs = script[2];
const helmet = xdc.slice(xdc.indexOf('<helmet>') + 8, xdc.indexOf('</helmet>'));
const css = (helmet.match(/<style>([\s\S]*?)<\/style>/) || [])[1] || '';
let template = xdc.slice(xdc.indexOf('</helmet>') + 9).replace(/<!--[\s\S]*?-->/g, '');
for (const [from, to] of Object.entries(ASSET_PATHS)) template = template.split(from).join(to);

const TAG = /<(\/?)([A-Za-z][\w-]*)((?:\s+[^\s=>/]+(?:="[^"]*")?)*)\s*(\/?)>/g;
const ATTR = /([^\s=>/]+)(?:="([^"]*)")?/g;

function parse(text) {
  const root = { tag: null, attrs: [], kids: [] };
  const stack = [root];
  let pos = 0;
  for (const m of text.matchAll(TAG)) {
    if (m.index > pos) {
      const t = text.slice(pos, m.index);
      if (t.trim()) stack.at(-1).kids.push(t.replace(/\s+/g, ' '));
    }
    pos = m.index + m[0].length;
    const [, closing, name, attrs, selfClose] = m;
    if (closing) {
      if (stack.at(-1).tag !== name) throw new Error(`mismatched </${name}> (open: ${stack.at(-1).tag})`);
      stack.pop();
      continue;
    }
    const node = { tag: name, attrs: [...attrs.matchAll(ATTR)].map((a) => [a[1], a[2] ?? '']), kids: [] };
    stack.at(-1).kids.push(node);
    if (!selfClose && !VOID.has(name)) stack.push(node);
  }
  if (stack.length !== 1) throw new Error(`unclosed <${stack.at(-1).tag}>`);
  return root.kids;
}

const HOLE_SPLIT = /\{\{\s*([\w.]+)\s*\}\}/;
const HOLE_ONLY = /^\{\{\s*([\w.]+)\s*\}\}$/;

/** A template string → JS expression. A lone hole keeps its raw value (functions, numbers, booleans). */
function expr(value) {
  const parts = value.split(HOLE_SPLIT);
  if (parts.length === 3 && parts[0] === '' && parts[2] === '') return `L(S,${JSON.stringify(parts[1])})`;
  const out = [];
  parts.forEach((p, i) => {
    if (i % 2) out.push(`str(L(S,${JSON.stringify(p)}))`);
    else if (p) out.push(JSON.stringify(p));
  });
  return out.length ? out.join('+') : '""';
}

const gen = (nodes) => nodes.map(genNode).filter(Boolean).join(',');

function genNode(n) {
  if (typeof n === 'string') return expr(n);
  const attrs = Object.fromEntries(n.attrs);
  if (n.tag === 'sc-for') {
    const list = attrs.list.trim().match(HOLE_ONLY)[1];
    return `...(L(S,${JSON.stringify(list)})||[]).map((it)=>((S)=>[${gen(n.kids)}])(scope(S,${JSON.stringify(attrs.as)},it)))`;
  }
  if (n.tag === 'sc-if') {
    const v = attrs.value.trim().match(HOLE_ONLY)[1];
    return `...(L(S,${JSON.stringify(v)})?[${gen(n.kids)}]:[])`;
  }
  const props = n.attrs
    .filter(([a]) => !a.startsWith('hint-placeholder'))
    .map(([a, v]) => `${JSON.stringify(a === 'tabindex' ? 'tabIndex' : a)}:${expr(v)}`);
  return `h(${JSON.stringify(n.tag)},{${props.join(',')}},${gen(n.kids)})`;
}

const controls = Object.fromEntries(Object.entries(propsSpec).filter(([k]) => !k.startsWith('$')));
const js = `// Generated by scripts/build-shelf.mjs from src/shelf/Shelf.dc.html.
// Do not edit by hand: change the .dc.html and run \`npm run shelf\`.
import { h } from 'preact';

const str = (v) => (v === undefined || v === null || v === false ? '' : String(v));
function scope(parent, name, value) { const s = Object.create(parent); s[name] = value; return s; }
function L(S, path) { let v = S; for (const k of path.split('.')) { if (v === undefined || v === null) return undefined; v = v[k]; } return v; }

class DCLogic {
  constructor(props) { this.props = props || {}; this.state = {}; this.onChange = null; }
  setState(u) {
    const n = typeof u === 'function' ? u(this.state) : u;
    if (n) { this.state = { ...this.state, ...n }; if (this.onChange) this.onChange(); }
  }
}
${logicJs}
export { Component };

export function renderTree(V) { const S = V; return [${gen(parse(template))}]; }

export const CONTROLS = ${JSON.stringify(controls, null, 2)};
`;

writeFileSync(OUT_JS, js);
writeFileSync(OUT_CSS, `/* Generated by scripts/build-shelf.mjs from the <helmet> of src/shelf/Shelf.dc.html. */\n${css.trim()}\n`);
console.log(`shelf: compiled ${SRC.replace(ROOT + '/', '')} → ${OUT_JS.replace(ROOT + '/', '')} (${Math.round(js.length / 1024)} KB)`);
